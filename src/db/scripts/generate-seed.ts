// Writes init/02-seed.sql from the typed content in src/web/data/, so the database starts with the same content as the site.
// Run after changing src/web/data: npm run seed (Node 22.18+ runs TypeScript directly, no install needed)
import { writeFileSync } from "node:fs";
import { calendarEvents } from "../../web/data/calendar.ts";
import { galleries } from "../../web/data/galleries.ts";
import { gallerySections } from "../../web/data/gallerySections.ts";
import { linkGroups, links } from "../../web/data/links.ts";
import { people } from "../../web/data/people.ts";
import { photos, puzzlePictures } from "../../web/data/photos.ts";
import { sponsors } from "../../web/data/sponsors.ts";

type Value = string | number | boolean | string[] | undefined;

const literal = (value: Value): string => {
  if (value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) return value.length ? `ARRAY[${value.map(literal).join(", ")}]` : "'{}'";
  return `'${value.replaceAll("'", "''")}'`;
};

// One INSERT per table, one line per row
const insert = (table: string, rows: Record<string, Value>[]) => {
  if (rows.length === 0) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((c) => literal(row[c])).join(", ")})`);
  return `INSERT INTO ${table} (${columns.join(", ")}) VALUES\n${values.join(",\n")};\n`;
};

const sql = [
  "-- Generated by scripts/generate-seed.ts from src/web/data/. Do not edit by hand.\n",
  "BEGIN;\n",
  insert(
    "link_groups",
    linkGroups.map((g, i) => ({ id: g.id, page: g.page, title: g.title, sort_order: i })),
  ),
  insert(
    "links",
    links.map((l, i) => ({
      id: l.id,
      group_id: l.groupId,
      title: l.title,
      href: l.href,
      description: l.description ?? [],
      details: l.details,
      sort_order: i,
    })),
  ),
  insert(
    "galleries",
    galleries.map((g, i) => ({
      id: g.id,
      folder: g.folder,
      unit: g.unit,
      year: g.year,
      title: g.title,
      date_text: g.dateText,
      url: g.url,
      sort_order: i,
    })),
  ),
  insert(
    "gallery_sections",
    gallerySections.map((s, i) => ({ unit: s.unit, title: s.title, href: s.href, cover: s.cover, sort_order: i })),
  ),
  insert(
    "people",
    people.map((p, i) => ({
      id: p.id,
      title_before: p.titleBefore,
      first_name: p.firstName,
      last_name: p.lastName,
      title_after: p.titleAfter,
      name: p.name,
      labels: p.labels,
      position: p.position,
      email: p.email,
      description: p.description ?? [],
      sort_order: i,
    })),
  ),
  insert(
    "phones",
    people.flatMap((p) =>
      (p.phones ?? []).map((phone, i) => ({ person_id: p.id, kind: phone.kind, number: phone.number, sort_order: i })),
    ),
  ),
  insert(
    "calendar_events",
    calendarEvents.map((e) => ({
      id: e.id,
      school_year: e.schoolYear,
      date: e.date,
      end_date: e.endDate,
      holiday: e.holiday ?? false,
      text: e.text,
    })),
  ),
  insert(
    "sponsors",
    sponsors.map((s, i) => ({ id: s.id, name: s.name, logo: s.logo, sort_order: i })),
  ),
  insert(
    "photos",
    [
      ...photos.map((p) => ({ ...p, collection: "school" })),
      ...puzzlePictures.map((p) => ({ ...p, collection: "puzzle" })),
    ].map((p, i) => ({ id: p.id, collection: p.collection, src: p.src, alt: p.alt, sort_order: i })),
  ),
  "COMMIT;\n",
].join("\n");

writeFileSync(new URL("../init/02-seed.sql", import.meta.url), sql);
console.log("Wrote init/02-seed.sql");
